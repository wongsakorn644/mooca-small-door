export function reflectionFor({ emotions, time, text }) {
  if (!emotions.length) {
    if (text) return 'ขอบคุณที่เล่าให้มูก้าฟังนะ แค่ได้เอาออกมาจากหัว ก็เบาลงไปนิดนึงแล้ว'
    return 'วันนี้แค่อยากพักก็พอแล้วนะ'
  }
  const first = emotions[0].id
  const line = REFLECT[first][time] || REFLECT[first].skip
  const rest = emotions.length - 1
  return rest > 0 ? `${line} และอีก ${rest} อย่างที่เธอถือมาด้วย มูก้ารับไว้หมดแล้วนะ` : line
}

